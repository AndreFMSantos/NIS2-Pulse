// Command genciphers generates internal/tlsprobe/ciphers_gen.go from the IANA
// TLS Cipher Suites registry, so the catalog is exact instead of typed by hand.
//
// Usage:
//
//	curl -O https://www.iana.org/assignments/tls-parameters/tls-parameters-4.csv
//	go run ./tools/genciphers -csv tls-parameters-4.csv -date 2026-11-06 \
//	    -out internal/tlsprobe/ciphers_gen.go
package main

import (
	"bytes"
	"encoding/csv"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const sourceURL = "https://www.iana.org/assignments/tls-parameters/tls-parameters-4.csv"

type entry struct {
	id   uint16
	name string
	rec  byte
}

var valueRE = regexp.MustCompile(`^0x([0-9A-Fa-f]{2}),0x([0-9A-Fa-f]{2})$`)

// parse reads the registry and returns its named, single-value suites sorted by ID.
// Ranges, "Reserved" and "Unassigned" rows are skipped.
func parse(r io.Reader) ([]entry, error) {
	cr := csv.NewReader(r)
	cr.FieldsPerRecord = -1
	rows, err := cr.ReadAll()
	if err != nil {
		return nil, err
	}
	if len(rows) == 0 || len(rows[0]) < 4 || rows[0][0] != "Value" || rows[0][1] != "Description" || rows[0][3] != "Recommended" {
		return nil, errors.New("unexpected CSV header: this is not the IANA TLS cipher suite registry")
	}

	seen := map[uint16]string{}
	var out []entry
	for _, row := range rows[1:] {
		if len(row) < 4 {
			continue
		}
		m := valueRE.FindStringSubmatch(strings.TrimSpace(row[0]))
		if m == nil {
			continue // a range such as 0x00,0x1C-1D
		}
		name := strings.TrimSpace(row[1])
		if name == "" || strings.HasPrefix(name, "Reserved") || strings.HasPrefix(name, "Unassigned") {
			continue
		}
		hi, _ := strconv.ParseUint(m[1], 16, 8)
		lo, _ := strconv.ParseUint(m[2], 16, 8)
		id := uint16(hi<<8 | lo)

		rec := strings.TrimSpace(row[3])
		if rec != "Y" && rec != "N" && rec != "D" {
			return nil, fmt.Errorf("suite %s has Recommended=%q, expected Y, N or D", name, rec)
		}
		if prev, dup := seen[id]; dup {
			return nil, fmt.Errorf("duplicate suite ID 0x%04X (%s and %s)", id, prev, name)
		}
		seen[id] = name
		out = append(out, entry{id, name, rec[0]})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].id < out[j].id })
	return out, nil
}

// render produces the gofmt-ed Go source of the catalog.
func render(entries []entry, date string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/genciphers from the IANA TLS Cipher Suites registry; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: %s (retrieved %s).\n\n", sourceURL, date)
	fmt.Fprintf(&b, "package tlsprobe\n\n")
	fmt.Fprintf(&b, "// Suites lists every named TLS cipher suite of the IANA registry, ordered by ID.\n")
	fmt.Fprintf(&b, "// Rec is the registry's \"Recommended\" column: 'Y' recommended, 'N' not recommended\n")
	fmt.Fprintf(&b, "// (not necessarily flawed), 'D' discouraged (SHOULD NOT or MUST NOT be used).\n")
	fmt.Fprintf(&b, "var Suites = []Suite{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t{0x%04X, %q, '%c'},\n", e.id, e.name, e.rec)
	}
	fmt.Fprintf(&b, "}\n")
	return format.Source(b.Bytes())
}

func main() {
	csvPath := flag.String("csv", "", "path to tls-parameters-4.csv")
	out := flag.String("out", "internal/tlsprobe/ciphers_gen.go", "output file")
	date := flag.String("date", "", "date the CSV was retrieved (YYYY-MM-DD)")
	flag.Parse()
	if *csvPath == "" || *date == "" {
		fmt.Fprintln(os.Stderr, "usage: genciphers -csv <file> -date <YYYY-MM-DD> [-out <file>]")
		os.Exit(2)
	}

	f, err := os.Open(*csvPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "genciphers:", err)
		os.Exit(1)
	}
	defer func() { _ = f.Close() }()

	entries, err := parse(f)
	if err != nil {
		fmt.Fprintln(os.Stderr, "genciphers:", err)
		os.Exit(1)
	}
	src, err := render(entries, *date)
	if err != nil {
		fmt.Fprintln(os.Stderr, "genciphers:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "genciphers:", err)
		os.Exit(1)
	}
	fmt.Printf("genciphers: %d suites written to %s\n", len(entries), *out)
}
