package main

import (
	"strings"
	"testing"
)

const sample = `Value,Description,DTLS-OK,Recommended,Reference,Comment
"0x00,0x00",TLS_NULL_WITH_NULL_NULL,Y,N,[RFC 5246],
"0x00,0x0A",TLS_RSA_WITH_3DES_EDE_CBC_SHA,Y,D,[RFC 5246],
"0x00,0x1C-1D",Reserved to avoid conflicts with SSLv3,Y,N,[RFC 5246],
"0x00,0x47-4F",Reserved to avoid conflicts with deployed implementations,,,[Pasi_Eronen],
"0x00,0x62",Unassigned,,,,
"0x00,0xFF",TLS_EMPTY_RENEGOTIATION_INFO_SCSV,Y,N,[RFC 5746],
"0x13,0x01",TLS_AES_128_GCM_SHA256,Y,Y,[RFC 8446],
"0x0A,0x0A",Reserved,Y,N,[RFC 8701],
"0xC0,0x2F",TLS_ECDHE_RSA_WITH_AES_128_GCM_SHA256,Y,Y,[RFC 5289],
"0xFE,0xFE",Reserved to avoid conflicts with deployed implementations,,,[RFC 5246],
`

func TestParseKeepsOnlyNamedSingleValueSuites(t *testing.T) {
	got, err := parse(strings.NewReader(sample))
	if err != nil {
		t.Fatal(err)
	}
	want := []entry{
		{0x0000, "TLS_NULL_WITH_NULL_NULL", 'N'},
		{0x000A, "TLS_RSA_WITH_3DES_EDE_CBC_SHA", 'D'},
		{0x00FF, "TLS_EMPTY_RENEGOTIATION_INFO_SCSV", 'N'},
		{0x1301, "TLS_AES_128_GCM_SHA256", 'Y'},
		{0xC02F, "TLS_ECDHE_RSA_WITH_AES_128_GCM_SHA256", 'Y'},
	}
	if len(got) != len(want) {
		t.Fatalf("got %d entries %v, want %d", len(got), got, len(want))
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("entry %d = %+v, want %+v", i, got[i], want[i])
		}
	}
}

func TestParseSortsByID(t *testing.T) {
	got, err := parse(strings.NewReader("Value,Description,DTLS-OK,Recommended,Reference,Comment\n" +
		"\"0xC0,0x2F\",TLS_B,Y,Y,x,\n\"0x00,0x0A\",TLS_A,Y,Y,x,\n"))
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || got[0].id != 0x000A || got[1].id != 0xC02F {
		t.Fatalf("entries must be sorted by ID, got %+v", got)
	}
}

func TestParseRejectsDuplicateIDs(t *testing.T) {
	_, err := parse(strings.NewReader("Value,Description,DTLS-OK,Recommended,Reference,Comment\n" +
		"\"0x00,0x0A\",TLS_A,Y,Y,x,\n\"0x00,0x0A\",TLS_B,Y,Y,x,\n"))
	if err == nil {
		t.Fatal("a duplicate cipher suite ID means the input is not what we expect")
	}
}

func TestParseRejectsAnUnexpectedHeader(t *testing.T) {
	if _, err := parse(strings.NewReader("a,b,c\n1,2,3\n")); err == nil {
		t.Fatal("an unexpected header must be an error, not an empty catalog")
	}
}

func TestParseRejectsAnUnknownRecommendedValue(t *testing.T) {
	_, err := parse(strings.NewReader("Value,Description,DTLS-OK,Recommended,Reference,Comment\n" +
		"\"0x00,0x0A\",TLS_A,Y,Q,x,\n"))
	if err == nil {
		t.Fatal("the Recommended column only means Y, N or D; anything else must stop the generator")
	}
}

func TestRenderIsGofmtStableAndMentionsTheSource(t *testing.T) {
	src, err := render([]entry{{0x000A, "TLS_RSA_WITH_3DES_EDE_CBC_SHA", 'D'}}, "2026-11-06")
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"Code generated by tools/genciphers",
		"DO NOT EDIT",
		"https://www.iana.org/assignments/tls-parameters/tls-parameters-4.csv",
		"2026-11-06",
		`{0x000A, "TLS_RSA_WITH_3DES_EDE_CBC_SHA", 'D'}`,
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("generated source lacks %q:\n%s", want, src)
		}
	}
}
